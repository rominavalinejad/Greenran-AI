"""Render results/results.md and the README results block from files in results/."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _f(x, n=2):
    return f"{x:.{n}f}"


def render(root: Path) -> str:
    r = root / "results"
    s = pd.read_csv(r / "summary.csv")
    meta = json.load(open(r / "run_meta.json"))
    fc = pd.read_csv(r / "forecast_metrics.csv")
    L = [f"_Generated by `make_report.py` from `results/` (run: seeds {meta['seeds']}, "
         f"{meta['n_squares']} grid squares -> {meta['n_sites']} sites, test {meta['split']['test'][0]}..{meta['split']['test'][1]}, "
         f"{meta['test_site_hours']} site-hours, quick={meta['quick']}, total runtime {meta['runtime_total_s']} s)._", "",
         "| Strategy | Energy saving vs always-on % (95% CI) | QoS violation site-hours % (95% CI) | Unserved traffic % (95% CI) | Mean solve time per site-day (s) |",
         "|---|---|---|---|---|"]
    for _, x in s.iterrows():
        rt = "-" if pd.isna(x.get("solve_mean_s")) else _f(x.solve_mean_s, 4)
        L.append(f"| {x.strategy} | {_f(x.saving_pct)} [{_f(x.saving_pct_lo)}, {_f(x.saving_pct_hi)}] | "
                 f"{_f(x.violation_rate_pct)} [{_f(x.violation_rate_pct_lo)}, {_f(x.violation_rate_pct_hi)}] | "
                 f"{_f(x.unserved_pct,3)} [{_f(x.unserved_pct_lo,3)}, {_f(x.unserved_pct_hi,3)}] | {rt} |")
    L += ["", "Point estimates are means over seeds; CIs are a paired site-day cluster bootstrap on the first seed. "
          "Seed-to-seed SD of saving / violation rate is in `results/summary.csv`.", "",
          "**Forecast quality on test (mean over seeds):**", ""]
    m = fc.drop(columns=["seed"]).mean()
    L.append("| Metric | Value |"); L.append("|---|---|")
    for k, v in m.items():
        L.append(f"| {k} | {_f(v,3)} |")
    p = r / "paired_differences.csv"
    if p.exists():
        d = pd.read_csv(p)
        L += ["", "**Paired differences (A − B, percentage points, 95% bootstrap CI):**", "",
              "| A | B | Metric | Diff | CI |", "|---|---|---|---|---|"]
        for _, x in d.iterrows():
            L.append(f"| {x.a} | {x.b} | {x.metric} | {_f(x.diff_mean)} | [{_f(x.lo)}, {_f(x.hi)}] |")
    sp = r / "sensitivity_power.csv"
    if sp.exists():
        d = pd.read_csv(sp)
        keep = d[d.strategy.isin(["threshold_80", "cpsat_point", "cpsat_point_x1.10", "cpsat_q90", "cpsat_q95"])]
        L += ["", "**Power-model sensitivity (seed 0, re-optimised):** saving % / violation %", "",
              "| p0 | p_sleep | e_switch | " + " | ".join(keep.strategy.unique()) + " |",
              "|---|---|---|" + "---|" * keep.strategy.nunique()]
        for (p0, ps, es), g in keep.groupby(["p0", "p_sleep", "e_switch"], sort=False):
            cells = [f"{_f(x.saving_pct,1)} / {_f(x.violation_rate_pct,1)}" for _, x in g.iterrows()]
            L.append(f"| {p0:g} | {ps:g} | {es:g} | " + " | ".join(cells) + " |")
    return "\n".join(L)


def write_report(root: Path):
    body = render(root)
    (root / "results" / "results.md").write_text("# GreenRAN AI results\n\n" + body + "\n")
    rd = root / "README.md"
    if rd.exists():
        t = rd.read_text()
        if START in t and END in t:
            t = t.split(START)[0] + START + "\n" + body + "\n" + END + t.split(END)[1]
            rd.write_text(t)


if __name__ == "__main__":
    write_report(Path(__file__).parent)


def plot_frontier(root: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    s = pd.read_csv(root / "results" / "summary.csv")
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for fam, mk in [("threshold", "s"), ("cpsat_point", "o"), ("cpsat_q", "^"), ("always_on", "x")]:
        g = s[s.strategy.str.startswith(fam)]
        ax.errorbar(g.saving_pct, g.violation_rate_pct,
                    yerr=[g.violation_rate_pct - g.violation_rate_pct_lo, g.violation_rate_pct_hi - g.violation_rate_pct],
                    xerr=[g.saving_pct - g.saving_pct_lo, g.saving_pct_hi - g.saving_pct], fmt=mk, label=fam, capsize=2)
        for _, x in g.iterrows():
            ax.annotate(x.strategy.replace("cpsat_", ""), (x.saving_pct, x.violation_rate_pct), fontsize=7,
                        xytext=(3, 3), textcoords="offset points")
    ax.set_xlabel("Energy saving vs always-on (%)"); ax.set_ylabel("QoS violation site-hours (%)")
    ax.set_title("Energy-QoS trade-off on test period (95% bootstrap CI)"); ax.grid(alpha=.3); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(root / "results" / "frontier.png", dpi=130)


def write_report_v6(root: Path, out_dir: Path | None = None) -> None:
    """Render results_v6.md from the files in out_dir (default: results_v6/ under root)."""
    r = Path(out_dir) if out_dir else root / "results_v6"
    meta = json.load(open(r / "run_meta_v6.json"))

    def tab(df):
        L = ["| Strategy | Saving % (95% CI) | QoS violation % (95% CI) | Unserved % (95% CI) |", "|---|---|---|---|"]
        for _, x in df.iterrows():
            L.append(f"| {x.strategy} | {_f(x.saving_pct)} [{_f(x.saving_pct_lo)}, {_f(x.saving_pct_hi)}] | "
                     f"{_f(x.violation_rate_pct)} [{_f(x.violation_rate_pct_lo)}, {_f(x.violation_rate_pct_hi)}] | "
                     f"{_f(x.unserved_pct,3)} [{_f(x.unserved_pct_lo,3)}, {_f(x.unserved_pct_hi,3)}] |")
        return L

    def ptab(df):
        L = ["| A | B | Metric | Diff (pp) | 95% CI |", "|---|---|---|---|---|"]
        for _, x in df.iterrows():
            L.append(f"| {x.a} | {x.b} | {x.metric} | {_f(x.diff_mean)} | [{_f(x.lo)}, {_f(x.hi)}] |")
        return L

    cov = pd.read_csv(r / "coverage.csv").groupby("quantile").mean(numeric_only=True).reset_index()
    L = ["# GreenRAN AI v6 results", "",
         f"_Generated by `make_report.py` from `results_v6/` (command `{meta['command']}`, commit {meta['git_commit'][:7]}"
         f"{' (dirty)' if meta['git_dirty'] else ''}, seeds {meta['seeds']}, {meta['n_bootstrap']} bootstrap draws, "
         f"{meta['bootstrap']}, runtime {meta['runtime_total_s']} s). Protocol: `protocol_v6.md`._", "",
         "## A. Coverage on test (mean over seeds)", "",
         "| Quantile | Nominal % | Raw val % | Raw test % | Conformal test % |", "|---|---|---|---|---|"]
    for _, x in cov.iterrows():
        L.append(f"| {x['quantile']} | {_f(x.nominal_pct,0)} | {_f(x.raw_val_coverage_pct)} | {_f(x.raw_test_coverage_pct)} | {_f(x.conformal_test_coverage_pct)} |")
    L += ["", "### Planning on test, one-shot", ""] + tab(pd.read_csv(r / "conformal_summary.csv"))
    L += ["", ""] + ptab(pd.read_csv(r / "conformal_paired.csv"))
    m = pd.read_csv(r / "matched_energy_test.csv")
    L += ["", f"## B. Matched energy (target validation saving {_f(meta['matched_target_val_saving_pct'])} % = point x1.10)", "",
          "| Strategy | Val saving % | Val violation % |", "|---|---|---|"]
    for _, x in m.dropna(subset=["family"]).iterrows():
        L.append(f"| {x.strategy} | {_f(x.val_saving_pct)} | {_f(x.val_violation_rate_pct)} |")
    L += ["", "Test:", ""] + tab(m) + ["", ""] + ptab(pd.read_csv(r / "matched_energy_paired.csv"))
    L += ["", "## C. Rolling day-by-day vs one-shot", ""] + tab(pd.read_csv(r / "rolling_vs_oneshot.csv"))
    L += ["", ""] + ptab(pd.read_csv(r / "rolling_vs_oneshot_paired.csv"))
    rc = pd.read_csv(r / "rolling_coverage.csv")
    L += ["", f"Rolling q90 coverage (mean over seeds and days): raw {_f(rc.raw_q90_coverage_pct.mean())} %, "
          f"conformal {_f(rc.conformal_q90_coverage_pct.mean())} %.", ""]
    (r / "results_v6.md").write_text("\n".join(L))
